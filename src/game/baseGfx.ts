// Real Bosconian base graphics, extracted from the ROM.
//
// Not hand-drawn: these are the exact tile codes and colour attributes the
// game's own base-draw routine (sub CPU 0x03d6) writes into the tilemap. They
// were captured by executing that routine directly in the Z80 core — no boot
// required — from the layout tables at sub ROM 0x0160 / 0x01a0 (tile codes)
// with their attribute tables at +0x100. See analysis/_execbase.ts.
//
// Each base is an 8x8 grid of 8x8 tiles (64x64 px). Tile 0x24 is blank.
// Attribute: bits 0-5 = colour set, bit 6 = flip X, bit 7 = flip Y.

export const BASE_BLANK_TILE = 0x24;
export const BASE_COLS = 8;
export const BASE_ROWS = 8;

export interface BaseGfx {
  codes: number[]; // 64 tile codes, row-major
  attrs: number[]; // 64 attributes, row-major
}

